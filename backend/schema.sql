CREATE TABLE enterprise_inquiries (
    inquiry_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(120 CHAR) NOT NULL,
    email VARCHAR2(254 CHAR) NOT NULL,
    service_slug VARCHAR2(40 CHAR) NOT NULL,
    message CLOB NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT enterprise_inquiries_service_fk
        FOREIGN KEY (service_slug) REFERENCES enterprise_services (slug)
);

CREATE INDEX enterprise_inquiries_created_idx
    ON enterprise_inquiries (created_at);

