CREATE TABLE enterprise_services (
    service_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR2(40 CHAR) NOT NULL UNIQUE,
    title VARCHAR2(100 CHAR) NOT NULL,
    description VARCHAR2(500 CHAR) NOT NULL,
    display_order NUMBER(2) NOT NULL,
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT enterprise_services_active_ck CHECK (is_active IN (0, 1))
);

